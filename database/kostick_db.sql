-- Database schema for Kostick Test System

CREATE DATABASE IF NOT EXISTS kostick_db;
USE kostick_db;

-- Users table
CREATE TABLE users (
    id INT AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    apellido_paterno VARCHAR(255),
    apellido_materno VARCHAR(255),
    apellido_casada VARCHAR(255),
    age INT NOT NULL,
    profession VARCHAR(255),
    ci_numero VARCHAR(20) NULL,
    ci_complemento VARCHAR(10) NULL,
    ci_full_key VARCHAR(40) GENERATED ALWAYS AS (
        CASE
            WHEN ci_numero IS NULL THEN NULL
            ELSE CONCAT(ci_numero, '#', COALESCE(ci_complemento, ''))
        END
    ) STORED,
    position_id INT NULL,
    position_name VARCHAR(255),
    CHECK (ci_numero IS NOT NULL OR ci_complemento IS NULL)
);

CREATE TABLE positions (
    id INT AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    normalized_name VARCHAR(255) NOT NULL UNIQUE,
    is_enabled TINYINT(1) NOT NULL DEFAULT 1,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

-- Tests table
CREATE TABLE tests (
    id INT AUTO_INCREMENT PRIMARY KEY,
    user_id INT,
    start_datetime DATETIME,
    end_datetime DATETIME,
    duration TIME,
    FOREIGN KEY (user_id) REFERENCES users(id)
);

-- Results table (one row per scale per test)
CREATE TABLE results (
    id INT AUTO_INCREMENT PRIMARY KEY,
    test_id INT,
    scale CHAR(1),
    score INT CHECK (score >= 0 AND score <= 20),
    level VARCHAR(10),
    FOREIGN KEY (test_id) REFERENCES tests(id)
);

-- Admin users table
CREATE TABLE admin_users (
    id INT AUTO_INCREMENT PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    is_active TINYINT(1) NOT NULL DEFAULT 1,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Access codes table (generated by admin)
CREATE TABLE access_codes (
    id INT AUTO_INCREMENT PRIMARY KEY,
    code VARCHAR(20) NOT NULL UNIQUE,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_inicio DATETIME NOT NULL,
    fecha_fin DATETIME NOT NULL,
    expires_at DATETIME NOT NULL,
    is_active TINYINT(1) NOT NULL DEFAULT 1,
    CHECK (fecha_fin > fecha_inicio)
);

ALTER TABLE users
ADD CONSTRAINT fk_users_position_id
FOREIGN KEY (position_id) REFERENCES positions(id)
ON DELETE SET NULL;
