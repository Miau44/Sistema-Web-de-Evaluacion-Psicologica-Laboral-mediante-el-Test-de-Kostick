CREATE INDEX IF NOT EXISTS idx_tests_user_id ON tests(user_id);
CREATE INDEX IF NOT EXISTS idx_results_test_id ON results(test_id);
CREATE INDEX IF NOT EXISTS idx_admin_users_username ON admin_users(username);
CREATE INDEX IF NOT EXISTS idx_access_codes_active_fecha_fin ON access_codes(is_active, fecha_fin);
CREATE INDEX IF NOT EXISTS idx_access_codes_window ON access_codes(is_active, fecha_inicio, fecha_fin);
CREATE INDEX IF NOT EXISTS idx_positions_enabled ON positions(is_enabled);
CREATE INDEX IF NOT EXISTS idx_positions_normalized_name ON positions(normalized_name);
CREATE INDEX IF NOT EXISTS idx_users_position_id ON users(position_id);
CREATE INDEX IF NOT EXISTS idx_users_ci_lookup ON users(ci_numero, ci_complemento);
