-- PostgreSQL schema for Kostick Test System
-- Database expected: kostick

-- Users table
CREATE TABLE IF NOT EXISTS users (
    id SERIAL PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    apellido_paterno VARCHAR(255),
    apellido_materno VARCHAR(255),
    apellido_casada VARCHAR(255),
    age INTEGER NOT NULL CHECK (age > 0),
    profession VARCHAR(255),
    ci_numero VARCHAR(20),
    ci_complemento VARCHAR(10),
    position_id INTEGER,
    position_name VARCHAR(255),
    CONSTRAINT chk_users_ci_numero_format CHECK (
        ci_numero IS NULL OR ci_numero ~ '^[0-9]{4,20}$'
    ),
    CONSTRAINT chk_users_ci_complemento_format CHECK (
        ci_complemento IS NULL OR ci_complemento ~ '^[A-Z0-9]{1,10}$'
    ),
    CONSTRAINT chk_users_ci_complement_requires_numero CHECK (
        ci_numero IS NOT NULL OR ci_complemento IS NULL
    )
);

CREATE TABLE IF NOT EXISTS positions (
    id SERIAL PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    normalized_name VARCHAR(255) NOT NULL UNIQUE,
    is_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Tests table
CREATE TABLE IF NOT EXISTS tests (
    id SERIAL PRIMARY KEY,
    user_id INTEGER REFERENCES users(id) ON DELETE CASCADE,
    start_datetime TIMESTAMP,
    end_datetime TIMESTAMP,
    duration TIME
);

-- Results table (one row per scale per test)
CREATE TABLE IF NOT EXISTS results (
    id SERIAL PRIMARY KEY,
    test_id INTEGER REFERENCES tests(id) ON DELETE CASCADE,
    scale CHAR(1) NOT NULL,
    score INTEGER NOT NULL CHECK (score >= 0 AND score <= 9),
    level VARCHAR(10) NOT NULL
);

-- Admin users table
CREATE TABLE IF NOT EXISTS admin_users (
    id SERIAL PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Access codes table (generated by admin)
CREATE TABLE IF NOT EXISTS access_codes (
    id SERIAL PRIMARY KEY,
    code VARCHAR(20) NOT NULL UNIQUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_inicio TIMESTAMP NOT NULL,
    fecha_fin TIMESTAMP NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_access_codes_valid_range CHECK (fecha_fin > fecha_inicio)
);

